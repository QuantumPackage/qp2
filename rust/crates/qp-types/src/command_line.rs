//! Command-line surface of the QP2 tools (`ocaml/Command_line.ml` and the
//! per-tool option tables in `ocaml/qp_*.ml`).
//!
//! The reference builds a list of [`Command_line`](https://) `description`
//! records, parses it with the vendored `getopt`, renders help with OCaml
//! `Format`, and checks only the *options* marked `Mandatory` centrally; each
//! `main` then matches its anonymous arguments and prints the help again
//! before failing. This port keeps the **observable contract** — which option
//! letters exist, which take values, the default values, and the exact failure
//! messages — and uses `clap` (derive) for the parsing. The structural
//! `description`/help-rendering layer is therefore not ported.
//!
//! Only the three tools whose executable is a straight `clap` port live here:
//! `qp_create_ezfio` ([`CreateArgs`]), `qp_edit` ([`EditArgs`]) and `qp_run`
//! ([`RunArgs`]). `qp_set_mo_class` and `qp_tunnel` were reworked (P4) into
//! statement-by-statement ports of the vendored `getopt` parser, which live
//! in their binaries; their `clap` structs here were dead and were removed
//! during the P5 CLI-parity audit, since a second parser can only drift.
//!
//! # Exit codes
//!
//! [`EXIT_USAGE`] is 2: every usage error, including `-h` (the reference
//! prints the help and *then* fails the anonymous-argument check), exits 2.
//! [`EXIT_FAILURE`] is 1 and is used only by `qp_edit` for failures raised
//! *inside* its `run` (banner `=-…`, backup restored). `qp_create_ezfio`
//! prints `"<tool>: <message>"` on standard error and exits 2.
//!
//! # Deliberate differences from the reference `getopt`/`Format`
//!
//! * Help text is generated by `clap` and is **not** byte-identical to the
//!   OCaml `Format` output (the reference byte counts are in
//!   `rust/CONTRACTS.md` §2.4). `-h` is still recognised by every tool and
//!   suppresses the mandatory-option check, as `set_specs` does: with
//!   [`CreateArgs::help`](CreateArgs) set, [`CreateArgs::validate`] lets a
//!   missing `-b` default to `""`, exactly as the reference `main` reads it.
//!   *Printing* the help (once, or twice because most tools call
//!   `Command_line.help` again before failing their anonymous-argument check)
//!   is the executable's job; these structs only expose the flag.
//! * An unknown option is rejected by `clap` with its own diagnostics and
//!   exit code 2, instead of
//!   `Fatal error: exception Getopt.Error("Unknown option --nope")`.
//! * `clap` rejects a value-taking option that is missing its value
//!   (`--basis` at end of argv) before [`validate`](CreateArgs::validate) can
//!   run; the reference raises
//!   `Getopt.Error("Option basis must have an argument")`.
//! * `clap` accepts `--name=value` and `--name value`, as `getopt` does, and
//!   `--` ends option parsing. It also accepts a value beginning with `-` as
//!   the immediate `-xVALUE` form, but not as the next argv element; that
//!   matches the vendored parser.
//!
//! # What is *not* done here
//!
//! Filesystem and EZFIO checks (whether the EZFIO directory exists, whether
//! the program is in `data/executables`, the `qp_edit` read/write
//! incompatibility) belong to the executables; the validated structs carry
//! the raw strings for them.

use std::fmt;

use clap::{ArgAction, Parser};

/// Exit code of a usage error (reference: every `main` exits 2 on a bad
/// command line, including after printing `-h` help).
pub const EXIT_USAGE: i32 = 2;

/// Exit code of a `qp_edit` failure raised inside its `run` (banner + exit 1).
pub const EXIT_FAILURE: i32 = 1;

/// A command-line failure whose message is the reference text.
///
/// The reference represents these as `Failure`/`Invalid_argument` exceptions;
/// the tool prefixes the message with its name (`"qp_create_ezfio: "`, …)
/// when it prints it. [`UsageError::to_string`] returns only the message.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UsageError {
    message: String,
}

impl UsageError {
    /// Build an error from the exact reference message.
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }

    /// The message without the tool prefix.
    #[must_use]
    pub fn message(&self) -> &str {
        &self.message
    }
}

impl fmt::Display for UsageError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for UsageError {}

/// `qp_create_ezfio` options (`ocaml/qp_create_ezfio.ml:700–825`).
#[derive(Debug, Clone, Parser)]
#[command(
    name = "qp_create_ezfio",
    disable_help_flag = true,
    disable_version_flag = true
)]
pub struct CreateArgs {
    /// Name of the created EZFIO directory.
    #[arg(short = 'o', long = "output", value_name = "EZFIO_DIR")]
    pub output: Option<String>,
    /// Name of the basis set (`base | Elem:base | i,Elem:base`). Mandatory.
    #[arg(short = 'b', long = "basis", value_name = "<string>")]
    pub basis: Option<String>,
    /// The input geometry is in atomic units.
    #[arg(short = 'a', long = "au", action = ArgAction::SetTrue)]
    pub au: bool,
    /// Total charge, with `m` for a minus sign (`m1` is -1).
    #[arg(short = 'c', long = "charge", value_name = "<int>")]
    pub charge: Option<String>,
    /// Add ghost atoms at `x * (covalent radius)`.
    #[arg(short = 'g', long = "ghost", value_name = "<float>")]
    pub ghost: Option<String>,
    /// Spin multiplicity `2S+1` (default 1).
    #[arg(short = 'm', long = "multiplicity", value_name = "<int>")]
    pub multiplicity: Option<String>,
    /// Pseudopotential name.
    #[arg(short = 'p', long = "pseudo", value_name = "<string>")]
    pub pseudo: Option<String>,
    /// Use the old (20210101) EZFIO conventions.
    #[arg(short = 'q', long = "qmc", action = ArgAction::SetTrue)]
    pub qmc: bool,
    /// Use Cartesian (6d, 10f, …) AOs.
    #[arg(short = 'x', long = "cartesian", action = ArgAction::SetTrue)]
    pub cartesian: bool,
    /// Print the help message.
    #[arg(short = 'h', long = "help", action = ArgAction::SetTrue)]
    pub help: bool,
    /// Input file in XYZ or Z-matrix format.
    #[arg(value_name = "FILE")]
    pub file: Vec<String>,
}

/// Validated `qp_create_ezfio` arguments, with the reference defaults.
#[derive(Debug, Clone, PartialEq)]
pub struct CreateConfig {
    /// `-o`: output EZFIO directory, or `None` for the derived name.
    pub output: Option<String>,
    /// `-b`: basis-set specification (may be empty if the user passed `-b ""`).
    pub basis: String,
    /// `-a`: the input is already in Bohr.
    pub au: bool,
    /// `-c`: total charge; `m<n>` means `-n`, default 0.
    pub charge: i64,
    /// `-g`: ghost-atom scale, default 0.
    pub ghost: f64,
    /// `-m`: spin multiplicity, default 1.
    pub multiplicity: i64,
    /// `-p`: pseudopotential name.
    pub pseudo: Option<String>,
    /// `-q`: old EZFIO conventions.
    pub qmc: bool,
    /// `-x`: Cartesian AOs.
    pub cartesian: bool,
    /// The **first** anonymous argument; extras are ignored by the reference.
    pub file: String,
}

impl CreateArgs {
    /// Apply the reference validation order: the mandatory `-b` option first,
    /// then the numeric values in declaration order, then the anonymous
    /// argument. When `-h` was given the mandatory check is skipped (as
    /// `set_specs` does) and a missing `-b` becomes `""`.
    ///
    /// # Errors
    ///
    /// [`UsageError`] carrying the exact reference message: `"--basis option
    /// is missing."`, `"int_of_string"`, `"float_of_string"`, or `"input
    /// file is missing"`.
    pub fn validate(self) -> Result<CreateConfig, UsageError> {
        let basis = match self.basis {
            Some(basis) => basis,
            // `set_specs` only checks mandatory options when `-h` is absent;
            // the reference `main` then reads a missing `-b` as `""`.
            None if self.help => String::new(),
            None => return Err(UsageError::new("--basis option is missing.")),
        };
        let charge = match self.charge {
            Some(text) => parse_charge(&text)?,
            None => 0,
        };
        let ghost = match self.ghost {
            Some(text) => text
                .parse::<f64>()
                .map_err(|_| UsageError::new("float_of_string"))?,
            None => 0.0,
        };
        let multiplicity = match self.multiplicity {
            Some(text) => text
                .parse::<i64>()
                .map_err(|_| UsageError::new("int_of_string"))?,
            None => 1,
        };
        let file = self
            .file
            .into_iter()
            .next()
            .ok_or_else(|| UsageError::new("input file is missing"))?;
        Ok(CreateConfig {
            output: self.output,
            basis,
            au: self.au,
            charge,
            ghost,
            multiplicity,
            pseudo: self.pseudo,
            qmc: self.qmc,
            cartesian: self.cartesian,
            file,
        })
    }
}

/// `qp_edit` options (`scripts/ezfio_interface/qp_edit_template`).
#[derive(Debug, Clone, Parser)]
#[command(
    name = "qp_edit",
    disable_help_flag = true,
    disable_version_flag = true
)]
pub struct EditArgs {
    /// Check the input data (no editor, no EZFIO write).
    #[arg(short = 'c', long = "check", action = ArgAction::SetTrue)]
    pub check: bool,
    /// Write the `qp_edit` file to this file.
    #[arg(short = 'w', long = "write", value_name = "<string>")]
    pub write: Option<String>,
    /// Read this file and apply it to the EZFIO.
    #[arg(short = 'r', long = "read", value_name = "<string>")]
    pub read: Option<String>,
    /// Truncate the wavefunction to this number of determinants.
    #[arg(short = 'n', long = "ndet", value_name = "<int>")]
    pub ndet: Option<String>,
    /// Extract these states, e.g. `"[1,3-5]"`.
    #[arg(short = 's', long = "state", value_name = "<range>")]
    pub state: Option<String>,
    /// Print the help message.
    #[arg(short = 'h', long = "help", action = ArgAction::SetTrue)]
    pub help: bool,
    /// EZFIO directory.
    #[arg(value_name = "EZFIO_DIR")]
    pub ezfio_dir: Vec<String>,
}

/// Validated `qp_edit` arguments.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EditConfig {
    /// `-c`.
    pub check: bool,
    /// `-w`.
    pub write: Option<String>,
    /// `-r`.
    pub read: Option<String>,
    /// `-n`, parsed with OCaml `int_of_string` semantics (decimal subset).
    pub ndet: Option<i64>,
    /// `-s`, parsed with `Range.of_string` semantics.
    pub state: Option<Vec<i64>>,
    /// The single anonymous argument.
    pub ezfio_dir: String,
}

impl EditArgs {
    /// Parse `-n` and `-s` (in that order) and require exactly one anonymous
    /// argument.
    ///
    /// The reference's read/write incompatibility is checked later, inside
    /// `run`, so it is not part of this validation.
    ///
    /// # Errors
    ///
    /// `"[-n|--ndet] expects an integer"`, `"[-s|--state] expects a range"`,
    /// or `"EZFIO_DIR is missing"`.
    pub fn validate(self) -> Result<EditConfig, UsageError> {
        let ndet = match self.ndet {
            Some(text) => Some(
                text.parse::<i64>()
                    .map_err(|_| UsageError::new("[-n|--ndet] expects an integer"))?,
            ),
            None => None,
        };
        let state = match self.state {
            Some(text) => Some(
                parse_state_range(&text)
                    .ok_or_else(|| UsageError::new("[-s|--state] expects a range"))?,
            ),
            None => None,
        };
        if self.ezfio_dir.len() != 1 {
            return Err(UsageError::new("EZFIO_DIR is missing"));
        }
        let ezfio_dir = self
            .ezfio_dir
            .into_iter()
            .next()
            .ok_or_else(|| UsageError::new("EZFIO_DIR is missing"))?;
        Ok(EditConfig {
            check: self.check,
            write: self.write,
            read: self.read,
            ndet,
            state,
            ezfio_dir,
        })
    }
}

/// `qp_run` options (`ocaml/qp_run.ml:232–270`).
#[derive(Debug, Clone, Parser)]
#[command(name = "qp_run", disable_help_flag = true, disable_version_flag = true)]
pub struct RunArgs {
    /// Slave mode (read `work/qp_run_address`).
    #[arg(short = 's', long = "slave", action = ArgAction::SetTrue)]
    pub slave: bool,
    /// Prefix before the program, e.g. `gdb` or `valgrind`.
    #[arg(short = 'p', long = "prefix", value_name = "<string>")]
    pub prefix: Option<String>,
    /// Print the help message.
    #[arg(short = 'h', long = "help", action = ArgAction::SetTrue)]
    pub help: bool,
    /// Program name and EZFIO directory, in that order.
    #[arg(value_name = "PROGRAM")]
    pub arguments: Vec<String>,
}

/// Validated `qp_run` arguments.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RunConfig {
    /// `-s`.
    pub slave: bool,
    /// `-p`.
    pub prefix: Option<String>,
    /// The program name (first anonymous argument).
    pub program: String,
    /// The EZFIO directory (second anonymous argument).
    pub ezfio_dir: String,
}

impl RunArgs {
    /// Require exactly two anonymous arguments.
    ///
    /// The directory-existence and executable-lookup checks happen in the
    /// executable, before any work.
    ///
    /// # Errors
    ///
    /// `"Inconsistent command line"`.
    pub fn validate(self) -> Result<RunConfig, UsageError> {
        if self.arguments.len() != 2 {
            return Err(UsageError::new("Inconsistent command line"));
        }
        let mut arguments = self.arguments.into_iter();
        let program = arguments
            .next()
            .ok_or_else(|| UsageError::new("Inconsistent command line"))?;
        let ezfio_dir = arguments
            .next()
            .ok_or_else(|| UsageError::new("Inconsistent command line"))?;
        Ok(RunConfig {
            slave: self.slave,
            prefix: self.prefix,
            program,
            ezfio_dir,
        })
    }
}

/// `qp_create_ezfio`'s charge syntax: a decimal integer, or `m<digits>` for a
/// negative value.
///
/// OCaml reads `x.[0]` first, so the empty string raises `Invalid_argument`
/// (uncaught by `qp_create_ezfio`); here it produces the `int_of_string`
/// message instead. Recorded in the port notes.
fn parse_charge(text: &str) -> Result<i64, UsageError> {
    match text.strip_prefix('m') {
        Some(digits) => digits
            .parse::<i64>()
            .map(|value| -value)
            .map_err(|_| UsageError::new("int_of_string")),
        None => text
            .parse::<i64>()
            .map_err(|_| UsageError::new("int_of_string")),
    }
}

/// `Range.of_string`: parse `"7"` or `"[1-3,5]"` into a sorted, duplicate-free
/// list, or `None` on any failure.
///
/// The caller collapses every failure to the single `qp_edit` message
/// `"[-s|--state] expects a range"`, so the error detail is not kept. The
/// grammar is the reference one: the first character decides between a single
/// integer and a bracketed list; each bracketed piece is split on its first
/// `-`; `""` contributes nothing; `start > finish` fails.
///
/// A huge range such as `"[1-100000000]"` allocates the whole list, exactly
/// as the reference does.
#[must_use]
pub fn parse_state_range(text: &str) -> Option<Vec<i64>> {
    let first = text.chars().next()?;
    let mut values = Vec::new();
    if first.is_ascii_digit() {
        values.push(text.parse::<i64>().ok()?);
    } else {
        if first != '[' || !text.ends_with(']') || text.len() < 2 {
            return None;
        }
        for piece in text[1..text.len() - 1].split(',') {
            match piece.split_once('-') {
                Some((start_text, finish_text)) => {
                    let start = start_text.parse::<i64>().ok()?;
                    let finish = finish_text.parse::<i64>().ok()?;
                    if start > finish {
                        return None;
                    }
                    values.extend(start..=finish);
                }
                None if piece.is_empty() => {}
                None => values.push(piece.parse::<i64>().ok()?),
            }
        }
    }
    values.sort_unstable();
    values.dedup();
    Some(values)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn create(argv: &[&str]) -> Result<CreateConfig, UsageError> {
        CreateArgs::try_parse_from(argv)
            .map_err(|error| UsageError::new(error.to_string()))?
            .validate()
    }

    fn edit(argv: &[&str]) -> Result<EditConfig, UsageError> {
        EditArgs::try_parse_from(argv)
            .map_err(|error| UsageError::new(error.to_string()))?
            .validate()
    }

    #[test]
    fn create_basics_and_defaults() {
        assert_eq!(
            create(&["qp_create_ezfio"]),
            Err(UsageError::new("--basis option is missing."))
        );
        assert_eq!(
            create(&["qp_create_ezfio", "-b", "cc-pvdz"]),
            Err(UsageError::new("input file is missing"))
        );
        let config = create(&[
            "qp_create_ezfio",
            "-b",
            "cc-pvdz",
            "-c",
            "m1",
            "-m",
            "3",
            "-g",
            "1.5",
            "-a",
            "-q",
            "-x",
            "-p",
            "bfd",
            "-o",
            "out",
            "mol.xyz",
            "ignored.xyz",
        ])
        .unwrap();
        assert_eq!(config.basis, "cc-pvdz");
        assert_eq!(config.charge, -1);
        assert_eq!(config.multiplicity, 3);
        assert_eq!(config.ghost, 1.5);
        assert!(config.au && config.qmc && config.cartesian);
        assert_eq!(config.pseudo.as_deref(), Some("bfd"));
        assert_eq!(config.output.as_deref(), Some("out"));
        assert_eq!(config.file, "mol.xyz");
        let defaults = create(&["qp_create_ezfio", "-b", "", "mol.xyz"]).unwrap();
        assert_eq!(defaults.charge, 0);
        assert_eq!(defaults.multiplicity, 1);
        assert_eq!(defaults.ghost, 0.0);
        assert_eq!(defaults.basis, "");
    }

    #[test]
    fn create_reports_the_reference_messages() {
        assert_eq!(
            create(&["qp_create_ezfio", "-b", "x", "-c", "x", "f"]),
            Err(UsageError::new("int_of_string"))
        );
        assert_eq!(
            create(&["qp_create_ezfio", "-b", "x", "-g", "x", "f"]),
            Err(UsageError::new("float_of_string"))
        );
        assert_eq!(
            create(&["qp_create_ezfio", "-b", "x", "-m", "x", "f"]),
            Err(UsageError::new("int_of_string"))
        );
    }

    #[test]
    fn edit_parses_the_state_range_and_ndet() {
        assert_eq!(
            edit(&["qp_edit"]),
            Err(UsageError::new("EZFIO_DIR is missing"))
        );
        assert_eq!(
            edit(&["qp_edit", "dir", "extra"]),
            Err(UsageError::new("EZFIO_DIR is missing"))
        );
        assert_eq!(
            edit(&["qp_edit", "-n", "x", "dir"]),
            Err(UsageError::new("[-n|--ndet] expects an integer"))
        );
        assert_eq!(
            edit(&["qp_edit", "-s", "x", "dir"]),
            Err(UsageError::new("[-s|--state] expects a range"))
        );
        let config = edit(&["qp_edit", "-c", "-n", "5", "-s", "[1,3-5]", "dir"]).unwrap();
        assert!(config.check);
        assert_eq!(config.ndet, Some(5));
        assert_eq!(config.state, Some(vec![1, 3, 4, 5]));
        assert_eq!(config.ezfio_dir, "dir");
    }

    #[test]
    fn run_requires_exactly_two_arguments() {
        let parse = |argv: &[&str]| {
            RunArgs::try_parse_from(argv)
                .map_err(|error| UsageError::new(error.to_string()))?
                .validate()
        };
        assert_eq!(
            parse(&["qp_run", "scf"]),
            Err(UsageError::new("Inconsistent command line"))
        );
        assert_eq!(
            parse(&["qp_run", "scf", "dir", "extra"]),
            Err(UsageError::new("Inconsistent command line"))
        );
        let config = parse(&["qp_run", "-s", "-p", "gdb", "scf", "dir"]).unwrap();
        assert!(config.slave);
        assert_eq!(config.prefix.as_deref(), Some("gdb"));
        assert_eq!(config.program, "scf");
        assert_eq!(config.ezfio_dir, "dir");
    }

    #[test]
    fn help_flag_is_recognised_by_every_tool() {
        assert!(
            CreateArgs::try_parse_from(["qp_create_ezfio", "-h"])
                .unwrap()
                .help
        );
        assert!(
            EditArgs::try_parse_from(["qp_edit", "--help"])
                .unwrap()
                .help
        );
        assert!(RunArgs::try_parse_from(["qp_run", "-h"]).unwrap().help);
        // `set_specs` skips the mandatory check when `-h` is seen, so a
        // missing `-b` is not reported; the anonymous check still runs.
        assert_eq!(
            create(&["qp_create_ezfio", "-h"]),
            Err(UsageError::new("input file is missing"))
        );
        let help = create(&["qp_create_ezfio", "-h", "mol.xyz"]).unwrap();
        assert_eq!(help.basis, "");
        assert_eq!(help.file, "mol.xyz");
    }

    #[test]
    fn state_range_matches_range_of_string() {
        assert_eq!(parse_state_range("7"), Some(vec![7]));
        assert_eq!(parse_state_range("[1-3,5]"), Some(vec![1, 2, 3, 5]));
        assert_eq!(
            parse_state_range("[72-73,36-37]"),
            Some(vec![36, 37, 72, 73])
        );
        assert_eq!(parse_state_range("[]"), Some(vec![]));
        assert_eq!(parse_state_range("[1,,2]"), Some(vec![1, 2]));
        assert_eq!(parse_state_range("[3-1]"), None);
        assert_eq!(parse_state_range("x"), None);
        assert_eq!(parse_state_range(""), None);
        assert_eq!(parse_state_range("[1"), None);
        assert_eq!(parse_state_range("1-3"), None);
    }

    #[test]
    fn exit_codes_are_the_measured_ones() {
        assert_eq!(EXIT_USAGE, 2);
        assert_eq!(EXIT_FAILURE, 1);
    }
}
