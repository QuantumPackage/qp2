//! `covalent_radius`, `vdw_radius`, `mass`, all 119 constructors).
//!
//! Lengths are in **bohr**: `covalent_radius` and `vdw_radius` return
//! `Units::ANGSTROM_TO_BOHR * r` exactly as OCaml does (the Angstrom
//! literals below are the ones written in `Element.ml`). `mass` is in
//! atomic mass units and is not converted.
//!
//! The OCaml module wraps the two radii in `Positive_float`, which raises
//! on a negative or NaN value; the table is non-negative by construction
//! (`all_radii_are_non_negative` in the tests), so this module returns a
//! plain `f64` and documents the invariant instead of re-checking it.

