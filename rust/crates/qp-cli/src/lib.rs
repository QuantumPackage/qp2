pub use root::root;

/// Anything a QP2 command-line tool can fail with.
#[derive(Debug)]
pub enum Error {
    /// `$QP_ROOT` is unset and could not be derived from the executable path.
    ///
    /// The display form is the reference's `Qpackage.root` failure text, which
    /// names the variable: setting it is the fix in both cases.
    Root,
    /// `data/executables` could not be read.
    Executables {
        /// File that was read.
        path: PathBuf,
        /// Why the read failed.
        source: io::Error,
    },
    /// An OS call in [`ffi`] failed (an `Unix.Unix_error` in the reference).
    Os(ffi::Error),
    /// A child process could not be spawned or awaited.
    Io(io::Error),
    /// An EZFIO operation failed (`qp-ezfio`).
    EzFio(qp_ezfio::Error),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Root => f.write_str(
                "QP_ROOT environment variable is not set.\nPlease source the quantum_package.rc file.",
            ),
            Self::Executables { path, source } => {
                write!(f, "Sys_error({:?})", format!("{}: {source}", path.display()))
            }
            Self::Os(error) => error.fmt(f),
            Self::Io(error) => write!(f, "Sys_error({:?})", error.to_string()),
            Self::EzFio(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for Error {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Executables { source, .. } => Some(source),
            Self::Io(error) => Some(error),
            Self::EzFio(error) => Some(error),
            Self::Root | Self::Os(_) => None,
        }
    }
}

impl From<io::Error> for Error {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

impl From<ffi::Error> for Error {
    fn from(error: ffi::Error) -> Self {
        Self::Os(error)
    }
}

impl From<qp_ezfio::Error> for Error {
    fn from(error: qp_ezfio::Error) -> Self {
        Self::EzFio(error)
    }
}

/// Result type of this crate.
pub type Result<T> = std::result::Result<T, Error>;

#[cfg(test)]
mod tests {
    use super::*;

    /// The root failure text is the reference's, including its second line.
    #[test]
    fn root_error_text() {
        assert_eq!(
            Error::Root.to_string(),
            "QP_ROOT environment variable is not set.\nPlease source the quantum_package.rc file."
        );
    }
}
