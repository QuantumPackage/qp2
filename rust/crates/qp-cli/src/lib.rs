//! Shared CLI plumbing for the QP2 Rust tools.
//!
//! The reference OCaml tools share four pieces of machinery that every
//! executable used, and which the Rust ports of `qp_run`, `qp_edit`,
//! `qp_create_ezfio` and the rest therefore need in one place:
//!
//! * [`root`] — `$QP_ROOT`. The reference reads the environment variable and
//!   fails when it is unset ([`root::root`] does the same); when it *is* unset
//!   the Rust tools derive the root from [`std::env::current_exe`] instead of
//!   relying on a path baked at compile time (issue #224).
//! * [`executables`] — the `data/executables` table generated by the build,
//!   which maps a program name (`scf`, `cisd`, …) to the Fortran binary that
//!   implements it (`Qpackage.executables`).
//! * [`launch`] — the `Sys.command` equivalent: run a command line through
//!   `/bin/sh -c`, inherit the standard streams, and return the exit status
//!   with the reference's mapping (exit code, `255` when the shell was
//!   signalled).
//! * [`signal`] — the SIGUSR1 → `qp_stop` plumbing of `qp_run`
//!   (`ocaml/qp_run.ml:87-89`), plus [`stop::qp_stop`] for the command itself.
//!
//! # Units and conventions
//!
//! * Times are Unix epoch seconds (`i64`, like `Unix.time`) unless a
//!   [`std::time::Duration`] says otherwise.
//! * Ports are `u32`, as in [`qp_zmq::port_window`].
//! * Every user-visible message returned by [`Error`] is the reference's
//!   text, except the ones documented on the variant.
//!
//! # `unsafe`
//!
//! Four OS calls have no `std` equivalent and are the only `unsafe` code in
//! the workspace: `localtime_r`, `gethostname`, `getifaddrs` and `sigaction`.
//! They live in [`ffi`], one `// SAFETY:`-documented block each (PI decision,
//! wave 3).

