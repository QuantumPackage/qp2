#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Post-process the ninja files generated by IRPF90.

Two independent fixups, both applied to ``<module>/IRPF90_temp/build.ninja``
after irpf90 has written it:

1. ``fix_ninja_file`` converts linking commands that have many .o files to use
   response files (@file syntax), which fixes the "Argument list too long"
   error.
2. ``share_irp_module_compiles`` compiles each distinct ``*.irp.module.F90``
   stub once, into a content-addressed store under ``$QP_ROOT/src/.irp_shared``,
   and lets every module copy the shared object and module files. Only stubs
   with no ``use`` and no ``include`` are shared: those are plain ``module``
   declaration blocks. The others keep their original edge, because their
   compile needs the consumer's include path and module ordering. A full build
   otherwise repeats ~4600 stub compiles for 561 distinct texts.

Neither fixup changes a compile flag, a command line, or the order-only
dependencies of the edges it rewrites. Both are idempotent and both give up
(leaving the file untouched, the build then simply slower) instead of writing
a manifest that might not work.
"""

import hashlib
import os
import re
import subprocess
import sys


# Regex pattern to match $in variable without matching $include, $include_dir, etc.
# Matches $in followed by whitespace, end of line, or non-identifier characters
DOLLAR_IN_PATTERN = r'\$in(?=\s|$|[^a-zA-Z0-9_])'

# Compiler and linker keywords to identify rules that should use response files
COMPILER_KEYWORDS = ['$fc', '$cc', 'gfortran', 'ifort', 'gcc', 'g++', 'clang', 'ar']


def fix_ninja_file(ninja_file_path):
    """
    Read a ninja file and convert long linking commands to use response files.
    
    Args:
        ninja_file_path: Path to the ninja file to fix
    
    Returns:
        True if file was modified, False otherwise
    """
    if not os.path.exists(ninja_file_path):
        return False
    
    with open(ninja_file_path, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    modified = False
    new_lines = []
    i = 0
    
    while i < len(lines):
        line = lines[i]
        
        # Look for rule definitions that might be link rules
        if line.startswith('rule '):
            split_line = line.strip().split()
            rule_name = split_line[1] if len(split_line) > 1 else ''
            rule_lines = [line]
            i += 1
            
            # Collect all lines in this rule
            command_line_text = ''
            while i < len(lines) and not lines[i].startswith('rule ') and not lines[i].startswith('build '):
                # Only collect lines that are part of the rule (indented or empty)
                if lines[i].startswith('  ') or lines[i].startswith('\t') or lines[i].strip() == '':
                    rule_lines.append(lines[i])
                    # Extract command line for keyword checking
                    if lines[i].strip().startswith('command ='):
                        command_line_text = lines[i].strip()
                    i += 1
                else:
                    # Non-indented, non-empty line that's not rule/build = end of rule
                    break
            
            # Check if this is a linking rule and needs fixing
            rule_text = ''.join(rule_lines)
            
            # Look for link, archive, or similar commands with $in
            # Check command line specifically for keywords to avoid false positives
            command_line_lower = command_line_text.lower() if command_line_text else ''
            is_link_rule = ('$in' in rule_text and 
                           'rspfile' not in rule_text and
                           command_line_text and
                           any(keyword in command_line_lower for keyword in COMPILER_KEYWORDS))
            
            if is_link_rule:
                # This rule might benefit from response files
                fixed_rule = fix_link_rule_lines(rule_lines)
                new_lines.extend(fixed_rule)
                modified = True
            else:
                new_lines.extend(rule_lines)
        else:
            new_lines.append(line)
            i += 1
    
    if modified:
        # Write the modified content back
        with open(ninja_file_path, 'w', encoding='utf-8') as f:
            f.writelines(new_lines)
        return True
    
    return False


def fix_link_rule_lines(rule_lines):
    """
    Fix a rule to use response files.
    
    Args:
        rule_lines: List of lines making up the rule
    
    Returns:
        List of fixed lines
    """
    new_rule_lines = []
    command_line_idx = None
    
    # Find the command line
    for idx, line in enumerate(rule_lines):
        if line.strip().startswith('command ='):
            command_line_idx = idx
            break
    
    if command_line_idx is None:
        return rule_lines  # No command found, return as-is
    
    command_line = rule_lines[command_line_idx]
    
    # Replace $in with @$out.rsp in the command using the defined pattern
    new_command = re.sub(DOLLAR_IN_PATTERN, '@$out.rsp', command_line)
    
    # If nothing changed, this rule might not need fixing
    if new_command == command_line:
        return rule_lines
    
    # Build the new rule with rspfile support
    for idx, line in enumerate(rule_lines):
        if idx == command_line_idx:
            new_rule_lines.append(new_command)
            # Add rspfile directives right after the command
            # Preserve the exact indentation from the command line
            indent_match = re.match(r'^(\s*)', line)
            indent = indent_match.group(1) if indent_match else '  '
            new_rule_lines.append(f'{indent}rspfile = $out.rsp\n')
            new_rule_lines.append(f'{indent}rspfile_content = $in_newline\n')
        else:
            new_rule_lines.append(line)
    
    return new_rule_lines


# ---------------------------------------------------------------------------
# Sharing of IRPF90 module-stub compiles
# ---------------------------------------------------------------------------
#
# IRPF90 writes one ``<name>.irp.module.F90`` per module of the project, in
# every project: a full build repeats ~4600 stub compiles for 561 distinct
# texts. A stub that contains no ``use`` and no ``include`` is a pure
# ``module ... end module`` declaration block: it references no project
# context, so compiling its text once and copying the resulting ``.o`` and
# ``.mod`` is equivalent. Stubs that `use` or `include` another module keep
# their original edge: their compile needs the consumer's include path and
# module ordering.
#
# Shared objects live in a content-addressed store
#
#     <QP_ROOT>/src/.irp_shared/<key>/src/<H>.F90
#     <QP_ROOT>/src/.irp_shared/<key>/obj/<H>.o
#     <QP_ROOT>/src/.irp_shared/<key>/mod/<H>/<name>.mod
#
# <H> hashes the stub text, <key> hashes the compiler token, its flags (minus
# the -I paths, which only describe the module's own include search) and the
# compiler version. A flag change (-Ofast <-> -O2, -march=native) or a compiler
# upgrade therefore starts a fresh store instead of reusing a foreign .mod.
# The store is never garbage-collected: it is bounded by ~517 stubs (~20 MB),
# content-addressed, and safe to delete at any time.

STUB_SUFFIX = '.irp.module.F90'
SHARED_STORE_NAME = '.irp_shared'

# `build <obj>: compile_fortran_<id> <src> | <order-only deps>`
STUB_BUILD_RE = re.compile(r'^build (\S+): (compile_fortran_\d+) (\S+)(?: \| (.*))?$')
# `use` or `include` at the start of a statement (possibly after `;`). A stub
# that matches is context-dependent and keeps its original edge (spec rev 2 §4.3).
STUB_CONTEXT_RE = re.compile(r'(?:^|;)[ \t]*(?:use|include)\b',
                             re.IGNORECASE | re.MULTILINE)
# Fortran is case-insensitive; the name is lowercased for the .mod file name.
MODULE_DECL_RE = re.compile(r'^\s*module\s+(\w+)', re.IGNORECASE | re.MULTILINE)
# `   key = value` line of a build edge
EDGE_VAR_RE = re.compile(r'^(\s+)(\w+)\s*=\s*(.*)$')
# The tail every compile_fortran_<id> command must end with (spec §4.2).
COMPILE_TAIL = '-c $src -o $out'


def _warn(message):
    """Print one warning to stderr; the build keeps working, only slower."""
    print(f'fix_ninja_response_files: {message}', file=sys.stderr)


def _chomp(line):
    """Drop the trailing newline of a physical line, if any."""
    return line[:-1] if line.endswith('\n') else line


def _split_logical_lines(lines):
    """
    Join ninja logical lines, the way ninja itself reads them.

    A line continues on the next one when it ends with an unescaped ``$``
    (``$$`` is a literal dollar sign, so only an odd number of trailing dollars
    continues). Joining removes the ``$`` and the newline, as ninja does.

    Args:
        lines: Physical lines, line endings included.

    Returns:
        A list of ``(text, ending, raw)`` tuples. ``text`` is the joined line
        without its line ending, ``ending`` is the line ending of the last
        physical line, and ``raw`` is the list of physical lines to emit when
        the logical line is left untouched.
    """
    items = []
    i = 0
    while i < len(lines):
        raw = [lines[i]]
        text = _chomp(lines[i])
        while text.endswith('$') and (len(text) - len(text.rstrip('$'))) % 2 == 1:
            if i + 1 >= len(lines):
                break
            i += 1
            raw.append(lines[i])
            text = text[:-1] + _chomp(lines[i])
        items.append((text, '\n' if lines[i].endswith('\n') else '', raw))
        i += 1
    return items


def _render_item(item):
    """Render a tuple returned by ``_split_logical_lines`` unchanged."""
    text, ending, raw = item
    if len(raw) == 1:
        return raw[0]
    return text + ending


def _manifest_path(path, t_dir):
    """
    Resolve a path written with the ``$T`` variable of the manifest.

    Args:
        path: Path as it appears in the build statement, e.g. ``$T/a/b.F90``.
        t_dir: Value of the ``T=`` variable of the same manifest.

    Returns:
        An absolute path, or None when the shape is not understood.
    """
    if path.startswith('$T/'):
        return os.path.join(t_dir, path[3:])
    if path == '$T':
        return t_dir
    if os.path.isabs(path):
        return path
    return None


def _canonical_command(command):
    """
    Split a ``compile_fortran_<id>`` command into compiler and flags.

    The ``-I <path>`` pairs are dropped (they only describe the include search
    of the module being built), as is the ``-c $src -o $out`` tail.

    Args:
        command: The ``command =`` value of the rule.

    Returns:
        ``(compiler, flags)``, or None if the command does not have the
        expected shape.
    """
    if not command.endswith(COMPILE_TAIL):
        return None
    head = command[:-len(COMPILE_TAIL)].split()
    if not head or '$' in head[0]:
        return None
    fc = head[0]
    flags = []
    skip_next = False
    for token in head[1:]:
        if skip_next:
            skip_next = False
            continue
        if token == '-I':
            skip_next = True
            continue
        if token.startswith('-I'):
            continue
        if '$' in token:
            # A ninja variable here would be expanded in the shared rule,
            # where it is not defined: refuse to rewrite.
            return None
        flags.append(token)
    return fc, flags


def _rule_commands(items):
    """Map every rule name of a manifest to its ``command =`` value."""
    commands = {}
    current = None
    for text, _, _ in items:
        if text.startswith('rule '):
            split = text.split()
            current = split[1] if len(split) > 1 else None
        elif current is not None:
            if text.startswith((' ', '\t')):
                stripped = text.strip()
                if stripped.startswith('command ='):
                    commands[current] = stripped[len('command ='):].strip()
            elif text.strip():
                current = None
    return commands


def _shared_store(command, store_root, cache):
    """
    Locate the store entry matching a compile command.

    The key is ``sha256(" ".join(canonical_flags) + "|" + version)[:16]`` where
    ``canonical_flags`` is the compiler token followed by every flag but the
    ``-I <path>`` pairs, and ``version`` is ``<fc> -dumpversion``.

    Args:
        command: The ``command =`` value of the ``compile_fortran_<id>`` rule.
        store_root: ``<QP_ROOT>/src/.irp_shared``.
        cache: Dict memoising the result, keyed by the command text.

    Returns:
        ``(compiler, flags, store_dir)``, or None if the command cannot be
        canonicalised (unknown shape, or the compiler cannot be queried).
    """
    if command in cache:
        return cache[command]
    result = None
    canonical = _canonical_command(command)
    if canonical is not None:
        fc, flags = canonical
        try:
            version = subprocess.check_output(
                [fc, '-dumpversion'], stderr=subprocess.DEVNULL
            ).decode('utf-8', 'replace').strip()
        except (OSError, subprocess.SubprocessError):
            version = None
        if version is not None:
            key = hashlib.sha256(
                (' '.join([fc] + flags) + '|' + version).encode('utf-8')
            ).hexdigest()[:16]
            result = (fc, flags, os.path.join(store_root, key))
    cache[command] = result
    return result


def _store_stub(store_dir, stub_hash, data):
    """
    Freeze the text of a stub in the store, once.

    The directories are created on every call (a few stat calls per edge); the
    source copy is skipped when it already exists, because rewriting it would
    move its mtime past the shared objects and force a recompile in every
    module. The copy goes through a temporary name so that an interrupted run
    cannot leave a truncated stub under its final, content-addressed name.

    Args:
        store_dir: ``<store>/<key>``, the directory of this store entry.
        stub_hash: ``<H>``, sha256 of the stub bytes, first 16 hex digits.
        data: The exact bytes of the stub.
    """
    os.makedirs(os.path.join(store_dir, 'src'), exist_ok=True)
    os.makedirs(os.path.join(store_dir, 'obj'), exist_ok=True)
    os.makedirs(os.path.join(store_dir, 'mod', stub_hash), exist_ok=True)
    destination = os.path.join(store_dir, 'src', stub_hash + '.F90')
    if os.path.exists(destination):
        return
    # The pid keeps two modules' manifest generators apart: they run
    # concurrently, and a shared temporary name would interleave their bytes.
    temporary = destination + '.tmp' + str(os.getpid())
    with open(temporary, 'wb') as f:
        f.write(data)
    os.replace(temporary, destination)


def _rewrite_stub_edge(match, var_items, ninja_file_path, t_dir, stub_rule,
                       store):
    """
    Turn one stub compile edge into the shared edge plus the copy edge.

    Args:
        match: Match of ``STUB_BUILD_RE`` on the joined build statement.
        var_items: Items of the ``key = value`` lines of that edge.
        ninja_file_path: Manifest being written, for the warnings.
        t_dir: Value of the ``T=`` variable of the manifest.
        stub_rule: Name of the rule every stub edge of this manifest uses.
        store: ``(compiler, flags, store_dir)`` of that rule.

    Returns:
        ``(shared_edge, copy_edge, stub_hash)`` when the stub is shared;
        ``False`` when the text contains a ``use`` or an ``include`` (the edge
        is context-dependent and is left exactly as it is, counted as
        skipped); or None when the edge must be left untouched for another
        reason. A warning is printed in the None case.
    """
    obj = match.group(1)
    src = match.group(3)
    order_only = match.group(4)

    src_path = _manifest_path(src, t_dir)
    if src_path is None or ' ' in src_path:
        _warn(f'{ninja_file_path}: cannot resolve {src}, {obj} left unchanged')
        return None
    try:
        with open(src_path, 'rb') as f:
            data = f.read()
    except OSError as exc:
        _warn(f'{ninja_file_path}: cannot read {src_path} ({exc}), '
              f'{obj} left unchanged')
        return None

    # A stub that `use`s or `include`s another module is not context-free: its
    # compile needs that module's `.mod` and the edge's original ordering.
    # Leave it exactly as IRPF90 wrote it (spec rev 2 §4.3).
    if STUB_CONTEXT_RE.search(data.decode('latin-1')):
        return False

    names = sorted({name.lower() for name in
                    MODULE_DECL_RE.findall(data.decode('utf-8', 'replace'))})
    if not names:
        _warn(f'{ninja_file_path}: {src} declares no module, '
              f'{obj} left unchanged')
        return None

    stub_hash = hashlib.sha256(data).hexdigest()[:16]
    _store_stub(store[2], stub_hash, data)

    shared_src = f'$SHARED/src/{stub_hash}.F90'
    shared_obj = f'$SHARED/obj/{stub_hash}.o'
    moddir = f'$SHARED/mod/{stub_hash}'
    shared_mods = [f'{moddir}/{name}.mod' for name in names]

    # Keep every variable of the edge that describes what is compiled (in
    # practice short_in and short_out), verbatim; src is consumed by the
    # shared compile and the three others are rewritten below.
    dropped = ('src', 'obj', 'mod', 'shared_mod', 'moddir')
    keep = []
    for item in var_items:
        var_match = EDGE_VAR_RE.match(item[0])
        if var_match is None or var_match.group(2) not in dropped:
            keep.append(_render_item(item))
    kept_text = ''.join(keep)

    indent = '   '
    shared_edge = (
        f'build {shared_obj} | {" ".join(shared_mods)}: '
        f'compile_shared {shared_src}\n'
        f'{indent}src = {shared_src}\n'
        f'{indent}moddir = {moddir}\n'
        # The .mod publish loop of the rule reads $shared_mod, i.e. the exact
        # implicit outputs declared just above: no glob, and a missing .mod
        # fails the edge instead of being silently skipped.
        f'{indent}shared_mod = {" ".join(shared_mods)}\n'
        + kept_text
    )

    if len(names) == 1:
        local_mods = f'$T/{names[0]}.mod'
        mod_argument = local_mods
        shared_mod_argument = shared_mods[0]
    else:
        # `cp` takes a directory as its last argument and the .mod files keep
        # their name, so a single cp copies them all.
        local_mods = ' '.join(f'$T/{name}.mod' for name in names)
        mod_argument = '$T'
        shared_mod_argument = ' '.join(shared_mods)

    deps = f' | {order_only}' if order_only and order_only.strip() else ''
    copy_edge = (
        f'build {obj} | {local_mods}: copy_stub {shared_obj}{deps}\n'
        f'{indent}obj = {obj}\n'
        f'{indent}mod = {mod_argument}\n'
        f'{indent}shared_mod = {shared_mod_argument}\n'
        + kept_text
    )

    return shared_edge, copy_edge, stub_hash


def _shared_rules_text(fc, flags):
    """Return the two rule definitions the rewritten edges use."""
    return (
        'rule compile_shared\n'
        # Ninja turns `$$` into one literal `$`, so `$$$$` here reaches the
        # shell as `$$`, the pid of this edge's own shell.
        f'  command = mkdir -p $moddir.$$$$ && {fc} -I . {" ".join(flags)} '
        f'-c $src -o $out.$$$$ -J $moddir.$$$$ '
        f'&& if [ -e $out ] ; then rm -f $out.$$$$ ; '
        f'else mv -f $out.$$$$ $out ; fi '
        f'&& for m in $shared_mod ; do b=$$(basename $$m) ; '
        f'if [ -e $moddir/$$b ] ; then rm -f $moddir.$$$$/$$b ; '
        f'else mv -f $moddir.$$$$/$$b $moddir ; fi ; done '
        f'&& rm -rf $moddir.$$$$\n'
        '  description = F*  : $short_in\n'
        '  generator = 1\n'
        '\n'
        'rule copy_stub\n'
        '  command = cp $in $obj && cp $shared_mod $mod\n'
        '  description = S   : $short_in -> $short_out\n'
        '\n'
    )


def _share_irp_module_compiles(ninja_file_path, module_dir):
    """Body of ``share_irp_module_compiles``; may raise."""
    with open(ninja_file_path, 'r', encoding='utf-8') as f:
        items = _split_logical_lines(f.readlines())

    # Nothing to do on a manifest without stub edges (this also makes a second
    # run on an already rewritten file a no-op).
    if not any(STUB_SUFFIX in text for text, _, _ in items):
        return False

    t_dir = None
    for text, _, _ in items:
        if text.startswith('T='):
            t_dir = text[2:].strip()
            break
    if not t_dir:
        _warn(f'{ninja_file_path}: no T= variable, stub sharing skipped')
        return False

    module_abs = os.path.realpath(module_dir)
    qp_root = os.path.dirname(os.path.dirname(module_abs))
    store_root = os.path.join(qp_root, 'src', SHARED_STORE_NAME)
    for path in (module_abs, t_dir, store_root):
        if ' ' in path:
            _warn(f'{ninja_file_path}: path with a space ({path}), '
                  'stub sharing skipped')
            return False

    # All the stub edges of a manifest come from one compile_fortran_<id>
    # rule; take it from the first one.
    stub_rule = None
    for text, _, _ in items:
        match = STUB_BUILD_RE.match(text)
        if match is not None and match.group(3).endswith(STUB_SUFFIX):
            stub_rule = match.group(2)
            break
    if stub_rule is None:  # cannot happen after the check above
        return False

    commands = _rule_commands(items)
    store = _shared_store(commands.get(stub_rule, ''), store_root, {})
    if store is None:
        _warn(f'{ninja_file_path}: cannot canonicalise the command of rule '
              f'{stub_rule}, stub sharing skipped')
        return False

    out = []
    edge_count = 0
    distinct = set()
    emitted_shared = set()
    skipped_count = 0

    i = 0
    while i < len(items):
        match = STUB_BUILD_RE.match(items[i][0])
        if match is None or not match.group(3).endswith(STUB_SUFFIX):
            out.append(_render_item(items[i]))
            i += 1
            continue

        # The `key = value` lines of the edge follow it.
        j = i + 1
        var_items = []
        while (j < len(items) and items[j][0].startswith((' ', '\t'))
               and items[j][0].strip()):
            var_items.append(items[j])
            j += 1

        rewritten = None
        skipped = False
        if match.group(2) == stub_rule:
            rewritten = _rewrite_stub_edge(match, var_items, ninja_file_path,
                                           t_dir, stub_rule, store)
            if rewritten is False:
                # `use`/`include` stub: the edge and its variables stay as is.
                skipped = True
                rewritten = None
        else:
            _warn(f'{ninja_file_path}: {match.group(1)} uses rule '
                  f'{match.group(2)}, expected {stub_rule}; '
                  'edge left unchanged')

        if skipped:
            skipped_count += 1

        if rewritten is None:
            out.append(_render_item(items[i]))
            out.extend(_render_item(item) for item in var_items)
        else:
            shared_edge, copy_edge, stub_hash = rewritten
            # The same stub twice in one module is not expected (the module
            # name is part of the text); reuse the shared edge if it happens.
            if stub_hash not in emitted_shared:
                out.append(shared_edge)
                emitted_shared.add(stub_hash)
            out.append(copy_edge)
            edge_count += 1
            distinct.add(stub_hash)
        i = j

    if edge_count == 0:
        return False

    # `SHARED` goes above the first rule, and the two rules at the end of the
    # rule block: ninja requires a rule to be defined before it is used.
    shared_line = f'SHARED = {store[2]}\n'
    previous = next((k for k, line in enumerate(out)
                     if line.startswith('SHARED =')), None)
    if previous is not None:
        out[previous] = shared_line
    else:
        first_rule = next((k for k, line in enumerate(out)
                           if line.startswith('rule ')), None)
        if first_rule is None:
            _warn(f'{ninja_file_path}: no rule in the manifest, '
                  'stub sharing skipped')
            return False
        out.insert(first_rule, shared_line)

    if not any(line.startswith('rule compile_shared') for line in out):
        first_build = next((k for k, line in enumerate(out)
                            if line.startswith('build ')), None)
        if first_build is None:
            _warn(f'{ninja_file_path}: no build statement in the manifest, '
                  'stub sharing skipped')
            return False
        out[first_build:first_build] = [_shared_rules_text(store[0], store[1])]

    temporary = ninja_file_path + '.stubshare.tmp'
    with open(temporary, 'w', encoding='utf-8') as f:
        f.write(''.join(out))
    os.replace(temporary, ninja_file_path)

    print(f'shared stubs: {edge_count} edges, {len(distinct)} distinct, '
          f'{skipped_count} skipped (use/include)')
    return True


def share_irp_module_compiles(ninja_file_path, module_dir):
    """
    Share the IRPF90 module-stub compiles of one module through a store.

    Rewrites every ``build <obj>: compile_fortran_<id> <src>.irp.module.F90``
    edge of the manifest into a ``compile_shared`` edge that builds the object
    and the ``.mod`` files once in ``<QP_ROOT>/src/.irp_shared/<key>``, plus a
    ``copy_stub`` edge that copies them back into the module. The order-only
    dependencies of the original edge are preserved verbatim, and the local
    ``.mod`` is declared as an implicit output so that deleting it regenerates
    it. A stub whose text contains a ``use`` or an ``include`` is not
    context-free: its edge is left untouched and counted as skipped.

    Args:
        ninja_file_path: ``<module>/IRPF90_temp/build.ninja``.
        module_dir: The module directory, ``<QP_ROOT>/src/<module>``.

    Returns:
        True if the manifest was rewritten, False otherwise. No exception
        escapes: an unexpected shape prints one warning and leaves the file
        untouched, so the build still works (only slower).
    """
    try:
        return _share_irp_module_compiles(ninja_file_path, module_dir)
    except Exception as exc:  # the build must never break here
        _warn(f'stub sharing disabled for {ninja_file_path}: {exc!r}')
        return False


def process_module_ninja_files(module_path=None):
    """
    Process IRPF90-generated ninja files in a module or the entire source tree.
    
    Args:
        module_path: Path to a specific module directory, or None to process all
    """
    if module_path:
        # Process a specific module
        ninja_file = os.path.join(module_path, 'IRPF90_temp', 'build.ninja')
        if os.path.exists(ninja_file):
            fix_ninja_file(ninja_file)
            # Same file, same process: share the module-stub compiles.
            share_irp_module_compiles(ninja_file, module_path)
        return 0
    else:
        # Process all modules - for manual use
        qp_root = os.environ.get('QP_ROOT')
        if not qp_root:
            print("Error: QP_ROOT not set", file=sys.stderr)
            return 1
        
        src_dir = os.path.join(qp_root, 'src')
        
        if not os.path.isdir(src_dir):
            print(f"Source directory not found: {src_dir}", file=sys.stderr)
            return 1
        
        count = 0
        for root, dirs, files in os.walk(src_dir):
            if 'IRPF90_temp' in root:
                ninja_file = os.path.join(root, 'build.ninja')
                if os.path.exists(ninja_file):
                    if fix_ninja_file(ninja_file):
                        count += 1
                        print(f"Fixed: {ninja_file}")
                    # `root` is the IRPF90_temp directory of the module.
                    share_irp_module_compiles(ninja_file,
                                              os.path.dirname(root))
        
        if count > 0:
            print(f"\nFixed {count} ninja file(s)")
        else:
            print("No ninja files needed fixing")
        
        return 0


if __name__ == '__main__':
    # Get module path from command line or process all
    if len(sys.argv) > 1:
        module_path = sys.argv[1]
    else:
        module_path = None
    
    sys.exit(process_module_ninja_files(module_path))
